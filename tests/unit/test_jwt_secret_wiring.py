"""Regression tests for the JWT secret wiring (audit item U-02).

JWTManager must never fall back to a random per-process secret. The
secret has to be supplied explicitly or wired in from ConfigManager
(``security.jwt_secret``) by UnifiedSecurityManager /
get_security_manager, and construction without any secret must fail
with a clear reason (fail-secure).
"""

import pytest

import blncs.core.config as config_module
import blncs.core.unified_security as unified_security
from blncs.core.config import get_config
from blncs.core.unified_security import (
    JWTManager,
    UnifiedSecurityManager,
    get_security_manager,
)

SECRET_ENV_VARS = (
    "BLNCS_SECURITY_JWT_SECRET",
    "BLNCS_JWT_SECRET",
    "JWT_SECRET",
)


@pytest.fixture
def reset_globals(monkeypatch, tmp_path):
    """Isolate the config / security-manager singletons and the cwd.

    Running inside ``tmp_path`` keeps ConfigManager from picking up
    the repository's own ``config/*.json`` files (and keeps the
    default config file it creates out of the repository).
    """
    monkeypatch.chdir(tmp_path)
    saved_config = config_module._global_config
    saved_manager = unified_security._security_manager
    config_module._global_config = None
    unified_security._security_manager = None
    yield
    manager = unified_security._security_manager
    if manager is not None:
        manager.stop_background_cleanup()
    unified_security._security_manager = saved_manager
    config_module.reset_config()
    config_module._global_config = saved_config


def _clear_secret_env(monkeypatch):
    for name in SECRET_ENV_VARS:
        monkeypatch.delenv(name, raising=False)


class TestJWTManagerSecretRequired:
    def test_missing_secret_raises_with_reason(self):
        with pytest.raises(ValueError, match="JWT secret is required"):
            JWTManager()

    def test_empty_secret_raises_with_reason(self):
        with pytest.raises(ValueError, match="JWT secret is required"):
            JWTManager("")

    def test_explicit_secret_token_roundtrip(self):
        manager = JWTManager("unit-test-secret")
        assert manager.secret_key == "unit-test-secret"
        auth_token = manager.create_token("alice", permissions=["read"])
        verified = manager.verify_token(auth_token.token)
        assert verified is not None
        assert verified.user_id == "alice"


class TestSecurityManagerWiring:
    def test_production_without_secret_fails_with_reason(
        self, reset_globals, monkeypatch
    ):
        _clear_secret_env(monkeypatch)
        monkeypatch.setenv("BLNCS_ENV", "production")
        with pytest.raises(Exception, match="JWT secret"):
            get_security_manager()
        # The failed construction must not leave a half-built singleton.
        assert unified_security._security_manager is None

    def test_config_secret_is_wired_into_manager(self, reset_globals, monkeypatch):
        _clear_secret_env(monkeypatch)
        monkeypatch.delenv("BLNCS_ENV", raising=False)
        monkeypatch.setenv("BLNCS_SECURITY_JWT_SECRET", "wiring-test-secret")
        manager = get_security_manager()
        assert manager.jwt_manager.secret_key == "wiring-test-secret"
        report = manager.get_security_report()
        assert isinstance(report, dict)
        assert "policies" in report

    def test_development_autogenerated_secret_matches_config(
        self, reset_globals, monkeypatch
    ):
        _clear_secret_env(monkeypatch)
        monkeypatch.delenv("BLNCS_ENV", raising=False)
        # blncs_main builds the ConfigManager before the security
        # manager; the manager must end up with the very secret
        # ConfigManager auto-generated for development, not an
        # independent random one.
        config = get_config()
        assert config.security.jwt_secret
        manager = get_security_manager()
        assert manager.jwt_manager.secret_key == config.security.jwt_secret

    def test_explicit_secret_skips_config(self, reset_globals, monkeypatch):
        # Even in a production environment with no configured secret
        # (where ConfigManager construction would raise), an explicit
        # secret must be usable on its own.
        _clear_secret_env(monkeypatch)
        monkeypatch.setenv("BLNCS_ENV", "production")
        manager = UnifiedSecurityManager(jwt_secret="explicit-secret")
        try:
            assert manager.jwt_manager.secret_key == "explicit-secret"
        finally:
            manager.stop_background_cleanup()
